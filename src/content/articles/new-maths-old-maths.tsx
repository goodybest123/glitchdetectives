/**
 * Body of the article "The New Maths and Old Maths. Pick One."
 */
export function NewMathsOldMaths() {
  return (
    <>
      <p>
        If you went to school a few decades ago, mathematics may have looked something like this:
        your teacher introduced a topic, explained a formula, worked through examples on the board,
        and gave you exercises to practise. You were expected to reproduce the method.
      </p>
      <p>
        You memorised multiplication tables, learnt mathematical rules, practised calculations, and
        were assessed on how many questions you could answer correctly. Get the answer right and you
        were doing well. Get it wrong and you probably needed more practice.
      </p>
      <p>
        For many of us, that was what learning mathematics looked like. But the world has changed.
        The way children access information has changed, the tools they use have changed, and the
        skills they will need to navigate the future are changing too.
      </p>
      <p>
        So should the way we teach mathematics remain exactly the same? Let&apos;s look at the
        difference.
      </p>

      <h2>What does Old Maths look like?</h2>
      <p>
        By <em>Old Maths</em>, I mean a traditional, largely procedure-focused approach to
        mathematics education. It often puts the method and final answer first.
      </p>

      <h3>1. Memorising before understanding</h3>
      <p>
        Children may be taught rules, formulas, and procedures before they understand why those
        rules work. For example, a child might memorise that adding fractions requires a common
        denominator without understanding what a denominator represents or why the parts need to be
        the same size before they can be combined.
      </p>

      <h3>2. Focusing on the final answer</h3>
      <p>
        A child solves <strong>24 ÷ 4</strong> and writes <strong>6</strong>. The answer is correct,
        so the question is marked. But did the child understand division? Can they explain why the
        answer is 6 or represent the calculation with objects, drawings, or equal groups?
      </p>
      <p>The final answer does not always tell us what a child understands.</p>

      <h3>3. Repetition as the primary learning strategy</h3>
      <p>
        Children may be given 20 or 30 similar questions to practise. Practice matters: mathematical
        fluency takes repetition. But repeating a procedure without understanding it can leave
        children confident in familiar situations and unsure when a question is presented
        differently.
      </p>

      <h3>4. One expected method</h3>
      <p>
        The teacher demonstrates a method, and children are expected to follow it. A child who
        discovers another mathematically correct way to solve the problem may still be directed back
        to the teacher&apos;s preferred method.
      </p>

      <h3>5. Speed as a measure of ability</h3>
      <p>
        Finishing calculations quickly is sometimes treated as evidence of mathematical ability. But
        a child who takes longer to reason through a problem is not necessarily less capable than
        one who produces an answer immediately. Speed and understanding are not the same thing.
      </p>

      <h2>What does New Maths look like?</h2>
      <p>
        <em>New Maths</em> is a shift towards understanding mathematics, not simply performing
        calculations. It helps children understand what they are doing, why they are doing it, and
        how mathematical ideas connect to the world around them.
      </p>

      <h3>1. Understanding before memorising</h3>
      <p>
        Instead of simply telling a child that <strong>3/4 is greater than 1/2</strong>, we can use
        fraction strips, drawings, or real-life objects to help them see why. Children explore
        mathematical relationships before being expected to memorise rules.
      </p>

      <h3>2. The thinking matters as much as the answer</h3>
      <p>
        Imagine two children solving <strong>24 ÷ 4 = ?</strong>
      </p>
      <p>
        Child A writes: <strong>6</strong>.
      </p>
      <blockquote>
        Child B writes 6 and explains: “I shared 24 objects equally among four groups. Each group
        received six.”
      </blockquote>
      <p>
        Both children have the correct answer. But the second explanation gives us more information
        about the child&apos;s understanding. We want to know how children arrive at answers, not
        just whether they arrive at them.
      </p>

      <h3>3. Multiple ways to solve a problem</h3>
      <p>
        There is not always one way to approach a mathematical problem. To work out 18 + 7, a child
        might:
      </p>
      <ul>
        <li>Count forward from 18.</li>
        <li>Break 7 into 2 and 5, make 20, and then add 5.</li>
        <li>Use a number line or physical objects.</li>
        <li>Recognise that 18 + 7 is the same as 20 + 5.</li>
      </ul>
      <p>
        These are different strategies that lead to the same answer. Children deserve room to
        explore them.
      </p>

      <h3>4. Connecting mathematics to everyday life</h3>
      <p>
        Mathematics should not exist only in textbooks and worksheets. Children can explore
        fractions by sharing food, addition while shopping, multiplication by arranging objects, and
        measurement while cooking. When they see mathematics in familiar experiences, abstract ideas
        can become easier to understand.
      </p>

      <h3>5. Asking children to question and investigate</h3>
      <p>
        What happens when an answer looks correct but the reasoning is wrong? What if a calculation
        contains a mistake? Can a child identify it, explain what went wrong, and correct it?
      </p>
      <p>
        Children should not simply accept mathematical statements because they come from a textbook,
        teacher, or AI tool. They should develop the confidence to investigate.
      </p>

      <h2>A practical example: teaching fractions</h2>
      <p>Let&apos;s take the topic of fractions.</p>

      <h3>The Old Maths approach</h3>
      <p>
        The teacher writes <strong>1/2 + 1/4 = ?</strong> The child is taught to find a common
        denominator, convert the fractions, and add the numerators. Then the child practises several
        similar questions.
      </p>

      <h3>The New Maths approach</h3>
      <p>
        The teacher shows two visual representations of a whole. One is divided into two equal
        parts, with one part shaded. The other is divided into four equal parts, with one part
        shaded. Then the child is invited to investigate:
      </p>
      <ul>
        <li>What do you notice about the shaded parts?</li>
        <li>Are they the same size?</li>
        <li>How many quarter pieces would cover one half?</li>
        <li>Can you show why 1/2 is equivalent to 2/4?</li>
        <li>What would happen if we added another quarter?</li>
      </ul>
      <p>
        The child explores the relationship visually before moving towards the symbolic calculation.
        Both approaches can teach fraction addition, but the second gives the child an opportunity
        to understand the relationship behind the procedure.
      </p>

      <h2>But is everything about Old Maths bad?</h2>
      <p>Absolutely not.</p>
      <p>
        Children still need multiplication facts, number recognition, mathematical vocabulary,
        formulas, and procedural fluency. They need to practise calculations and remember important
        facts. The problem is not memorisation or practice. The problem is making memorisation and
        practice the entire learning experience.
      </p>
      <p>
        A child can know all their multiplication tables and still struggle to apply multiplication
        to a real-life problem. A child can memorise a formula and still have no idea when or why to
        use it. We should not abandon foundational skills; we should give children a reason to
        understand and use them.
      </p>

      <h2>And what about AI?</h2>
      <p>
        This conversation becomes even more important in the age of artificial intelligence.
        Children can now ask AI tools to solve calculations, explain mathematical concepts, and
        complete homework. A child can get an answer without necessarily understanding the process
        behind it.
      </p>
      <p>That means we need children who can:</p>
      <ul>
        <li>Question an answer instead of automatically accepting it.</li>
        <li>Check whether information is accurate.</li>
        <li>Identify errors in mathematical reasoning.</li>
        <li>Explain why a solution makes sense.</li>
        <li>Apply what they know to unfamiliar problems.</li>
      </ul>
      <p>
        The ability to obtain an answer is becoming easier. The ability to evaluate that answer is
        becoming increasingly important.
      </p>
      <p>
        This is one of the reasons I started building Glitch Detectives. I wanted to create learning
        experiences where children are not always starting with a blank page or simply being given
        answers to reproduce. Instead, they are presented with completed mathematical problems,
        including intentional mistakes. Their job is to investigate, identify the error, correct it,
        and explain their reasoning.
      </p>
      <p>
        We are not trying to replace mathematical foundations with technology. We are using a
        different learning experience to help children develop the mathematical thinking they need.
      </p>

      <h2>So, which one should we pick?</h2>
      <p>
        <strong>The New Maths.</strong>
      </p>
      <p>
        Not because everything about traditional mathematics is outdated, but because children
        deserve more than being trained to reproduce procedures. They deserve to understand what
        they are learning, explore different approaches, make mistakes without being discouraged,
        ask questions, and explain their reasoning.
      </p>
      <p>
        They need computational fluency, but they also need mathematical confidence, curiosity, and
        independent thinking. Most importantly, they need to know that getting an answer is only
        part of the process.
      </p>
      <p>
        <strong>
          We don&apos;t just want children who can solve mathematical problems. We want children who
          understand, question, investigate, and can explain why their answers make sense.
        </strong>
      </p>
      <p>That is the kind of mathematics education I believe we should be moving towards.</p>
      <p>
        So, I&apos;ll ask again: <strong>The New Maths or the Old Maths?</strong>
      </p>
      <p>I&apos;d pick New Maths. Every time.</p>
      <p>
        <strong>What would you pick?</strong>
      </p>
    </>
  );
}
